// Regenerates supabase/setup.sql (all migrations + seed in one paste-able file).
// Usage: npm run db:bundle            (write)
//        npm run db:bundle -- --check (exit 1 if setup.sql is out of date)
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const migrationsDir = path.join(root, "supabase", "migrations");
const target = path.join(root, "supabase", "setup.sql");

export function bundle() {
  const files = fs
    .readdirSync(migrationsDir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  const parts = [
    "-- Pawtopia one-shot setup: all migrations + seed data.",
    "-- Paste into Supabase Dashboard → SQL Editor → New query → Run (on a NEW project).",
    "-- Already ran an older setup.sql? Run only the migration files added since then, in order.",
    "-- GENERATED by `npm run db:bundle` from supabase/migrations/*.sql and supabase/seed.sql — do not edit.",
  ];
  for (const f of files)
    parts.push("", `-- ===== ${f} =====`, fs.readFileSync(path.join(migrationsDir, f), "utf8").trimEnd());
  parts.push(
    "",
    "-- ===== seed.sql =====",
    fs.readFileSync(path.join(root, "supabase", "seed.sql"), "utf8").trimEnd(),
    "",
  );
  return parts.join("\n");
}

if (process.argv[1] === import.meta.filename) {
  const content = bundle();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current !== content) {
      console.error("supabase/setup.sql is out of date — run `npm run db:bundle`.");
      process.exit(1);
    }
    console.log("supabase/setup.sql is up to date.");
  } else {
    fs.writeFileSync(target, content);
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}
