// Regenerates src/lib/database.types.ts from the public schema of a database
// that has the migrations applied (the local stack by default).
// Usage: npm run db:types            (write)
//        npm run db:types -- --check (exit 1 if the committed types are out of date)
// Database: $TEST_DATABASE_URL, else postgresql://postgres:postgres@127.0.0.1:54322/postgres
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import * as prettier from "prettier";

// Keep in step with the Supabase CLI version in .github/workflows/pawtopia-ci.yml.
const CLI_VERSION = "2.121.0";
const root = path.resolve(import.meta.dirname, "..");
const target = path.join(root, "src", "lib", "database.types.ts");
const dbUrl = process.env.TEST_DATABASE_URL ?? "postgresql://postgres:postgres@127.0.0.1:54322/postgres";

function generate() {
  try {
    return execFileSync(
      "npx",
      ["--yes", `supabase@${CLI_VERSION}`, "gen", "types", "typescript", "--db-url", dbUrl, "--schema", "public"],
      { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    );
  } catch (error) {
    console.error(error.stderr || error.message);
    console.error("Could not generate types. Is a database with the migrations applied running?");
    process.exit(1);
  }
}

const header =
  "// GENERATED by `npm run db:types` from the database schema (supabase/migrations) — do not edit.\n" +
  "// App-level shapes built on these live in ./types.ts.\n\n";
const config = await prettier.resolveConfig(target);
const content = await prettier.format(header + generate(), { ...config, filepath: target });

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== content) {
    console.error("src/lib/database.types.ts is out of date — run `npm run db:types` after changing migrations.");
    process.exit(1);
  }
  console.log("src/lib/database.types.ts is up to date.");
} else {
  fs.writeFileSync(target, content);
  console.log(`Wrote ${path.relative(root, target)}`);
}
